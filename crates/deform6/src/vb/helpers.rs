//! The Visual Basic idiom of each helper of the runtime.
//!
//! A native program calls `MSVBVM60.DLL` for most of what a Basic statement
//! does. This table gives the idiom that each helper carries out. The text
//! is a note beside an instruction. It is not a statement of the source.

/// Gives the idiom of the helper `name`, when this table knows it.
#[must_use]
pub fn idiom(name: &str) -> Option<&'static str> {
    Some(match name {
        "__vbaAryConstruct2" => "make a local array",
        "__vbaAryDestruct" => "free a local array",
        "__vbaAryLock" => "lock an array for an element access",
        "__vbaAryMove" => "a() = b(), and b() is emptied",
        "__vbaAryUnlock" => "unlock an array",
        "__vbaBoolVarNull" => "CBool(v), with Null as False",
        "__vbaChkstk" => "reserve a large stack frame",
        "__vbaCastObj" => "convert an object to an interface",
        "__vbaCopyBytes" => "copy bytes of a value",
        "__vbaEnd" => "End",
        "__vbaErase" => "Erase",
        "__vbaErrorOverflow" => "raise error 6, Overflow",
        "__vbaExitProc" => "leave a procedure that has On Error",
        "__vbaFPException" => "raise the error of a failed floating point operation",
        "__vbaFPInt" => "Int(x)",
        "__vbaFailedFriend" => "raise the error of a failed Friend call",
        "__vbaFileClose" => "Close #",
        "__vbaFileOpen" => "Open",
        "__vbaFpCSngR4" | "__vbaFpCSngR8" => "CSng(x)",
        "__vbaFpR4" => "CSng(x)",
        "__vbaFpI2" => "CInt(x)",
        "__vbaFpI4" => "CLng(x)",
        "__vbaFpUI1" => "CByte(x)",
        "__vbaFreeObj" | "__vbaFreeObjList" => "release temporary objects",
        "__vbaFreeStr" | "__vbaFreeStrList" => "release temporary strings",
        "__vbaFreeVar" | "__vbaFreeVarList" => "release temporary Variants",
        "__vbaGet3" | "__vbaGet4" | "__vbaGetOwner3" => "Get #",
        "__vbaHresultCheckObj" => "raise the error of a failed object call",
        "__vbaI2I4" => "CInt(long)",
        "__vbaI2Str" => "CInt(s)",
        "__vbaI2Var" => "CInt(v)",
        "__vbaI4Str" => "CLng(s)",
        "__vbaI4Var" => "CLng(v)",
        "__vbaInStr" => "InStr",
        "__vbaLateIdCall" | "__vbaLateIdCallLd" | "__vbaLateMemCall" | "__vbaLateMemCallLd" => {
            "late-bound call"
        }
        "__vbaLateIdSt" => "late-bound property assignment",
        "__vbaLbound" => "LBound",
        "__vbaLenBstr" => "Len(s)",
        "__vbaLenBstrB" => "LenB(s)",
        "__vbaLenVar" => "Len(v)",
        "__vbaLineInputStr" => "Line Input #",
        "__vbaLsetFixstrFree" => "LSet of a fixed string",
        "__vbaNew" => "New",
        "__vbaNew2" => "make the default instance when it does not exist",
        "__vbaObjSet" => "Set a = b",
        "__vbaObjSetAddref" => "Set a = b, with a new reference",
        "__vbaObjVar" => "the object in a Variant",
        "__vbaOnError" => "On Error",
        "__vbaPowerR8" => "a ^ b",
        "__vbaPrintFile" => "Print #",
        "__vbaPut3" | "__vbaPut4" | "__vbaPutOwner3" => "Put #",
        "__vbaR4Var" => "CSng(v)",
        "__vbaR8Cy" => "CDbl(currency)",
        "__vbaR8IntI2" | "__vbaR8IntI4" => "Int(x), as an integer",
        "__vbaR8FixI4" => "Fix(x), as an integer",
        "__vbaR8Str" => "CDbl(s)",
        "__vbaRecAnsiToUni" | "__vbaRecUniToAnsi" => "convert a record for a Declare call",
        "__vbaRecDestruct" | "__vbaRecDestructAnsi" => "free a record",
        "__vbaRedim" => "ReDim",
        "__vbaRedimPreserve" => "ReDim Preserve",
        "__vbaResume" => "Resume",
        "__vbaSetSystemError" => "save Err.LastDllError after a Declare call",
        "__vbaStrCat" => "a & b",
        "__vbaStrCmp" => "compare two strings",
        "__vbaStrCopy" => "a = b, with a copy of the string",
        "__vbaStrFixstr" => "a String from a fixed string",
        "__vbaStrI2" | "__vbaStrI4" | "__vbaStrR4" | "__vbaStrR8" | "__vbaStrUI1" => "CStr(x)",
        "__vbaStrMove" => "a = b, and b is a temporary string",
        "__vbaStrToAnsi" => "convert a string for a Declare call",
        "__vbaStrToUnicode" => "convert a string after a Declare call",
        "__vbaStrVarMove" | "__vbaStrVarVal" => "CStr(v)",
        "__vbaUI1I2" => "CByte(integer)",
        "__vbaUbound" => "UBound",
        "__vbaVar2Vec" => "an array from a Variant",
        "__vbaVarAdd" => "a + b, in Variants",
        "__vbaVarAnd" => "a And b, in Variants",
        "__vbaVarCat" => "a & b, in Variants",
        "__vbaVarCmpEq" | "__vbaVarTstEq" => "a = b, in Variants",
        "__vbaVarCmpGt" => "a > b, in Variants",
        "__vbaVarCmpLe" => "a <= b, in Variants",
        "__vbaVarCopy" | "__vbaVarDup" => "a = b, with a copy of the Variant",
        "__vbaVarDiv" => "a / b, in Variants",
        "__vbaVarForInit" => "For, with a Variant counter",
        "__vbaVarForNext" => "Next, with a Variant counter",
        "__vbaVarMove" | "__vbaVargVarMove" => "a = b, and b is a temporary Variant",
        "__vbaVarMul" => "a * b, in Variants",
        "__vbaVarNot" => "Not a, in Variants",
        "__vbaVarOr" => "a Or b, in Variants",
        "__vbaVarSub" => "a - b, in Variants",
        "__vbaVarTstNe" => "a <> b, in Variants",
        "_adj_fdiv_m32" | "_adj_fdiv_m64" => "a / b, with the Pentium divide correction",
        _ => return None,
    })
}
